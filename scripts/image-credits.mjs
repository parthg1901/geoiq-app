// Writes docs/IMAGE_CREDITS.md: author + licence for every bundled Wikimedia Commons image
// (region flags/arms from scripts/packs/build-regions.mjs, country arms from src/data/arms.json).
// Run after the image builds: node scripts/image-credits.mjs
import fs from 'node:fs';
import path from 'node:path';

const UA = { 'User-Agent': 'GeoIQ-build/1.0 (+https://github.com/parthg1901/geoiq-app)' };
const CACHE = 'scripts/.cache/credits';
fs.mkdirSync(CACHE, { recursive: true });

const strip = (s) => (s || '').replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

async function imageInfo(files) {
  const out = {};
  for (let i = 0; i < files.length; i += 40) {
    const chunk = files.slice(i, i + 40);
    const key = path.join(CACHE, `batch-${Buffer.from(chunk.join('|')).toString('base64url').slice(0, 60)}-${chunk.length}.json`);
    let j;
    if (fs.existsSync(key)) j = JSON.parse(fs.readFileSync(key, 'utf8'));
    else {
      const url = `https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=extmetadata&titles=${encodeURIComponent(chunk.map((f) => 'File:' + f).join('|'))}`;
      j = await (await fetch(url, { headers: UA })).json();
      fs.writeFileSync(key, JSON.stringify(j));
    }
    // Map normalized titles back to the requested names.
    const norm = Object.fromEntries((j.query?.normalized ?? []).map((n) => [n.to, n.from]));
    for (const pg of Object.values(j.query?.pages ?? {})) {
      const md = pg.imageinfo?.[0]?.extmetadata ?? {};
      const requested = (norm[pg.title] ?? pg.title).replace(/^File:/, '');
      out[requested] = {
        artist: strip(md.Artist?.value) || 'Unknown author',
        license: strip(md.LicenseShortName?.value) || 'see file page',
        page: `https://commons.wikimedia.org/wiki/${encodeURIComponent(pg.title.replace(/ /g, '_'))}`,
      };
    }
  }
  return out;
}

const regionSources = JSON.parse(fs.readFileSync('scripts/.cache/packs-regions/image-sources.json', 'utf8'));
const arms = JSON.parse(fs.readFileSync('src/data/arms.json', 'utf8'));
const armsFile = (a) => decodeURIComponent(a.page.split('/wiki/File:')[1] ?? '').replace(/_/g, ' ');
const files = [...new Set([...Object.values(regionSources), ...Object.values(arms).map(armsFile).filter(Boolean)])];
const info = await imageInfo(files);
const row = (label, file) => {
  const i = info[file] ?? { artist: 'Unknown author', license: 'see file page', page: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file.replace(/ /g, '_'))}` };
  return `| ${label} | [${file}](${i.page}) | ${i.artist.replace(/\|/g, '/')} | ${i.license} |`;
};
const lines = [
  '# Image credits',
  '',
  'Flags, coats of arms, emblems and seals bundled with GeoIQ come from [Wikimedia Commons](https://commons.wikimedia.org/).',
  'Most are public domain as official state symbols; the rest are used under the licence shown. Each entry links to the original file.',
  '',
  '_Generated by `scripts/image-credits.mjs` — do not edit by hand._',
  '',
  '## Countries — coats of arms, emblems and seals (`public/arms/`)',
  '',
  '| Country | File | Author | Licence |',
  '|---|---|---|---|',
  ...Object.entries(arms).sort().map(([id, a]) => row(`\`${id}\``, armsFile(a))),
  '',
  '## Regions — flags and coats of arms (`public/data/packs/img/`)',
  '',
  '| Image | File | Author | Licence |',
  '|---|---|---|---|',
  ...Object.entries(regionSources).sort().map(([dest, file]) => row(`\`${dest.replace('/data/packs/img/', '')}\``, file)),
  '',
];
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/IMAGE_CREDITS.md', lines.join('\n'));
const missing = files.filter((f) => !info[f]).length;
const lic = {};
for (const f of files) { const l = info[f]?.license ?? '?'; lic[l] = (lic[l] ?? 0) + 1; }
console.log(`credited ${files.length - missing}/${files.length} Commons files (${Object.keys(regionSources).length} region images + ${Object.keys(arms).length} country arms)`);
console.log('licences:', lic);
